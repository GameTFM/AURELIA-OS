#!/usr/bin/env python3
"""Generate AURELIA's embedded font atlases from open-source variable fonts.

Produces:
  kernel/include/generated/fonts.h   types, extern declarations, list
  kernel/generated/font_data.c       packed 8-bit alpha atlases + glyph tables

Each glyph stores its ink rectangle inside the atlas, bearings relative to the
text origin's top-left, and its advance width. The kernel renderer blends the
8-bit alpha coverage, so text is antialiased without any runtime font engine.
"""
from __future__ import annotations

import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "toolchain" / "fonts"
OUT_INC = ROOT / "kernel" / "include" / "generated"
OUT_SRC = ROOT / "kernel" / "generated"

ATLAS_WIDTH = 1024

# (c_identifier, file, weight, size_px, human name)
FACES = [
    ("font_ui_11", "Inter.ttf", 400, 11, "Inter 11 Regular"),
    ("font_ui_13", "Inter.ttf", 400, 13, "Inter 13 Regular"),
    ("font_ui_15", "Inter.ttf", 400, 15, "Inter 15 Regular"),
    ("font_ui_17", "Inter.ttf", 450, 17, "Inter 17 Medium"),
    ("font_ui_20", "Inter.ttf", 560, 20, "Inter 20 Semibold"),
    ("font_ui_28", "Inter.ttf", 600, 28, "Inter 28 Semibold"),
    ("font_display_64", "CormorantGaramond.ttf", 500, 64, "Cormorant 64"),
    ("font_display_96", "PlayfairDisplay.ttf", 500, 96, "Playfair 96"),
    ("font_mono_13", "JetBrainsMono.ttf", 400, 13, "JetBrains Mono 13"),
    ("font_mono_15", "JetBrainsMono.ttf", 400, 15, "JetBrains Mono 15"),
]

EXTRA_CODEPOINTS = [
    0x00A0, 0x00B0, 0x00B7, 0x00D7, 0x2013, 0x2014, 0x2018, 0x2019,
    0x201C, 0x201D, 0x2022, 0x2026, 0x2190, 0x2191, 0x2192, 0x2193,
    0x2212, 0x25CF, 0x2713, 0x00E9, 0x00FC, 0x00F6, 0x00E4,
]


def set_weight(font: ImageFont.FreeTypeFont, weight: float, optical: float) -> None:
    try:
        axes = font.get_variation_axes()
    except Exception:
        return
    values = []
    for axis in axes:
        name = axis.get("name", b"")
        if isinstance(name, bytes):
            name = name.decode("utf-8", "ignore")
        if "wght" in name.lower():
            values.append(weight)
        elif "opsz" in name.lower():
            values.append(optical)
        else:
            values.append(axis.get("default", 0))
    try:
        font.set_variation_by_axes(values)
    except Exception as exc:  # noqa: BLE001
        print("  variation failed:", exc)


def render_face(path: Path, weight: float, size: int):
    font = ImageFont.truetype(str(path), size)
    set_weight(font, weight, size)
    ascent, descent = font.getmetrics()

    codepoints = list(range(32, 127)) + EXTRA_CODEPOINTS
    glyphs = []
    shelf_x = 0
    shelf_y = 0
    shelf_h = 0
    placements = []

    for cp in codepoints:
        ch = chr(cp)
        try:
            advance = int(round(font.getlength(ch)))
        except Exception:
            advance = size // 2
        try:
            # Render into a generous canvas, then crop to the ink rectangle.
            pad = max(size, 8)
            canvas = Image.new("L", (size * 3 + 16, size * 3 + 16), 0)
            draw = ImageDraw.Draw(canvas)
            draw.text((pad, pad), ch, fill=255, font=font)
            bbox = canvas.getbbox()
        except Exception:
            bbox = None
        if bbox is None:
            placements.append({"cp": cp, "w": 0, "h": 0, "bx": 0, "by": 0,
                               "advance": advance, "ink": None})
            continue
        x0, y0, x1, y1 = bbox
        w = x1 - x0
        h = y1 - y0
        ink = canvas.crop((x0, y0, x1, y1))
        placements.append({
            "cp": cp, "w": w, "h": h,
            "bx": x0 - pad, "by": y0 - pad,
            "advance": advance, "ink": ink,
        })

    # Shelf-pack into the atlas.
    for item in placements:
        if item["w"] == 0 or item["h"] == 0:
            item["x"] = item["y"] = 0
            continue
        if shelf_x + item["w"] > ATLAS_WIDTH:
            shelf_x = 0
            shelf_y += shelf_h + 1
            shelf_h = 0
        item["x"] = shelf_x
        item["y"] = shelf_y
        shelf_x += item["w"] + 1
        shelf_h = max(shelf_h, item["h"])

    atlas_h = shelf_y + shelf_h + 1
    atlas = Image.new("L", (ATLAS_WIDTH, atlas_h), 0)
    for item in placements:
        if item["w"] and item["h"]:
            atlas.paste(item["ink"], (item["x"], item["y"]))

    return {
        "ascent": ascent, "descent": descent,
        "line_height": ascent + descent,
        "glyphs": placements,
        "atlas": atlas,
        "atlas_w": ATLAS_WIDTH, "atlas_h": atlas_h,
    }


def emit(faces):
    OUT_INC.mkdir(parents=True, exist_ok=True)
    OUT_SRC.mkdir(parents=True, exist_ok=True)

    header = []
    header.append("/* Generated by tools/genfont.py - do not edit by hand. */")
    header.append("#pragma once")
    header.append("")
    header.append("#include <aurelia/types.h>")
    header.append("")
    header.append("typedef struct {")
    header.append("    u32 codepoint;")
    header.append("    u16 atlas_x, atlas_y, w, h;")
    header.append("    i16 bearing_x, bearing_y;")
    header.append("    u16 advance;")
    header.append("} glyph_t;")
    header.append("")
    header.append("typedef struct {")
    header.append("    const char *name;")
    header.append("    u16 pixel_size, ascent, descent, line_height;")
    header.append("    u16 glyph_count;")
    header.append("    const glyph_t *glyphs;")
    header.append("    const u8 *bitmap;")
    header.append("    u16 atlas_width, atlas_height;")
    header.append("} font_t;")
    header.append("")
    for ident, _f, _w, _size, label in FACES:
        header.append("extern const font_t %s; /* %s */" % (ident, label))
    header.append("")
    header.append("extern const font_t *const g_font_list[];")
    header.append("extern const u32 g_font_count;")
    header.append("")

    src = ["/* Generated by tools/genfont.py - do not edit by hand. */",
           '#include <generated/fonts.h>', ""]

    for ident, _f, _w, size, label in FACES:
        data = faces[(ident, label)]
        blob = data["atlas"].tobytes()
        src.append("static const u8 %s_bitmap[] = {" % ident)
        for i in range(0, len(blob), 24):
            src.append("    " + ",".join(str(b) for b in blob[i:i + 24]) + ",")
        src.append("};")
        src.append("")
        src.append("static const glyph_t %s_glyphs[] = {" % ident)
        for g in data["glyphs"]:
            src.append("    { %d, %d, %d, %d, %d, %d, %d, %d }," % (
                g["cp"], g.get("x", 0), g.get("y", 0), g["w"], g["h"],
                g["bx"], g["by"], g["advance"]))
        src.append("};")
        src.append("")
        src.append("const font_t %s = {" % ident)
        src.append('    .name = "%s",' % label)
        src.append("    .pixel_size = %d, .ascent = %d, .descent = %d, .line_height = %d," % (
            size, data["ascent"], data["descent"], data["line_height"]))
        src.append("    .glyph_count = %d," % len(data["glyphs"]))
        src.append("    .glyphs = %s_glyphs," % ident)
        src.append("    .bitmap = %s_bitmap," % ident)
        src.append("    .atlas_width = %d, .atlas_height = %d," % (data["atlas_w"], data["atlas_h"]))
        src.append("};")
        src.append("")
        print("  %-16s %5dx%-5d glyphs=%-3d %6.1f KiB" % (
            ident, data["atlas_w"], data["atlas_h"], len(data["glyphs"]),
            len(blob) / 1024))

    src.append("const font_t *const g_font_list[] = {")
    for ident, _f, _w, _s, _l in FACES:
        src.append("    &%s," % ident)
    src.append("};")
    src.append("const u32 g_font_count = %d;" % len(faces))
    src.append("")

    (OUT_INC / "fonts.h").write_text("\n".join(header), encoding="utf-8")
    (OUT_SRC / "font_data.c").write_text("\n".join(src), encoding="utf-8")
    print("wrote %s and %s" % (OUT_INC / "fonts.h", OUT_SRC / "font_data.c"))


def main():
    faces = {}
    for ident, filename, weight, size, label in FACES:
        path = FONTS / filename
        if not path.exists():
            raise SystemExit("missing font: %s (run toolchain/bootstrap.py)" % path)
        print("rendering %s (%s, weight %d, %dpx)" % (ident, filename, weight, size))
        faces[(ident, label)] = render_face(path, weight, size)
    emit(faces)


if __name__ == "__main__":
    main()
