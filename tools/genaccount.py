#!/usr/bin/env python3
"""Generate the demo account credential header.

The kernel never stores the account password: only a salted SHA-256 digest is
compiled in. This is a demo credential for the single-user AURELIA alpha image.
"""
from __future__ import annotations

import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
USER = "aurelia"
SALT = "aurelia-solstice-demo-salt"
PASSWORD = "solstice"

digest = hashlib.sha256(SALT.encode() + PASSWORD.encode()).hexdigest()

header = f"""/* Generated by tools/genaccount.py - do not edit by hand. */
#pragma once

#define AURELIA_DEMO_USER "{USER}"
#define AURELIA_DEMO_SALT "{SALT}"
#define AURELIA_DEMO_HASH "{digest}"
"""

out = ROOT / "kernel" / "include" / "generated" / "account.h"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(header, encoding="ascii", newline="\n")
print(f"wrote {out} (user {USER}, salted sha256)")
